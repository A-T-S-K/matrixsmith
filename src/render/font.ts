const FALLBACK_GLYPH: readonly [number, number, number, number, number] = [0x7f, 0x41, 0x41, 0x41, 0x7f]; // hollow box

export function glyphColumns(character: string): readonly number[] {
  const code = character.codePointAt(0) ?? 0;
  if (code < 32 || code > 126) return FALLBACK_GLYPH;
  return FONT_5X7[code - 32] ?? FALLBACK_GLYPH;
}

/** Column bit-patterns for a whole string, one blank column between glyphs. */
export function textColumns(text: string): readonly number[] {
  const columns: number[] = [];
  for (const character of text) {
    columns.push(...glyphColumns(character));
    columns.push(0);
  }
  if (columns.length > 0) columns.pop();
  return columns;
}

/** Rendered width in columns for a text string in the embedded font. */
export function measureText(text: string): { readonly width: number; readonly height: number } {
  return { width: textColumns(text).length, height: GLYPH_HEIGHT };
}

export type TextAlignment = "left" | "center" | "right";

export interface RenderTextOptions {
  readonly color: { readonly r: number; readonly g: number; readonly b: number };
  readonly background?: { readonly r: number; readonly g: number; readonly b: number };
  readonly alignment?: TextAlignment;
  /** Horizontal pixel offset applied after alignment; used for scroll frames. */
  readonly offsetX?: number;
}

/**
 * Deterministically rasterize text into a logical framebuffer of the given
 * dimensions. Text is vertically centered; columns outside the canvas clip
 * without error (scrolling renders successive offsets of the same text).
 */
export function renderText(text: string, width: number, height: number, options: RenderTextOptions): Framebuffer {
  const frame = new Framebuffer(width, height);
  const background = options.background ?? { r: 0, g: 0, b: 0 };
  frame.fill(background.r, background.g, background.b);
  const columns = textColumns(text);
  const alignment = options.alignment ?? "left";
  const baseX = alignment === "left" ? 0 : alignment === "center" ? Math.floor((width - columns.length) / 2) : width - columns.length;
  const originX = baseX + (options.offsetX ?? 0);
  const originY = Math.max(0, Math.floor((height - GLYPH_HEIGHT) / 2));
  for (const [columnIndex, columnBits] of columns.entries()) {
    const x = originX + columnIndex;
    if (x < 0 || x >= width) continue;
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      const y = originY + row;
      if (y >= height) break;
      if ((columnBits >>> row) & 1) frame.setPixel(x, y, options.color.r, options.color.g, options.color.b);
    }
  }
  return frame;
}

/**
 * Compute the scroll offsets that carry text across a canvas once: entering
 * from the right edge and exiting fully to the left.
 */
export function scrollOffsets(text: string, width: number, step = 1): readonly number[] {
  if (!Number.isInteger(step) || step <= 0) throw new RangeError("Scroll step must be a positive integer.");
  const textWidth = textColumns(text).length;
  const offsets: number[] = [];
  for (let offset = width; offset >= -textWidth; offset -= step) offsets.push(offset);
  if (offsets[offsets.length - 1] !== -textWidth) offsets.push(-textWidth);
  return offsets;
}

