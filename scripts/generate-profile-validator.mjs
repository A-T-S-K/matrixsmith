import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { rolldown } from "rolldown";
import { format } from "prettier";

const outputIndex = process.argv.indexOf("--output");
const output =
  outputIndex < 0
    ? "src/profiles/generated/profile-validator.js"
    : process.argv[outputIndex + 1];
if (!output) throw new Error("Missing --output path.");
const schema = JSON.parse(
  readFileSync("public/profile-v1.schema.json", "utf8"),
);
const ajv = new Ajv2020({
  code: { source: true },
  allErrors: false,
  inlineRefs: false,
  loopRequired: 8,
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
});
const code = standaloneCode(ajv, ajv.compile(schema));
// Ajv standalone references ucs2length and fullFormats via CommonJS requires.
// Bundle these helpers, not the compiler, into a portable browser ESM module.
const entry = resolve("src/diagnostics/generated/validator-input.cjs");
const bundle = await rolldown({
  input: entry,
  platform: "browser",
  plugins: [
    {
      name: "local-validator",
      resolveId(id) {
        if (id === entry) return entry;
      },
      load(id) {
        if (id === entry) return code;
      },
      transform(source, id) {
        if (id.endsWith("/ajv/dist/runtime/equal.js"))
          return source.replace(/^equal\.code = .*;$/m, "");
        if (id.endsWith("/ajv/dist/runtime/ucs2length.js"))
          return source.replace(/^ucs2length\.code = .*;$/m, "");
      },
    },
  ],
});
const result = await bundle.generate({ format: "esm", comments: false });
await bundle.close();
const chunk = result.output[0];
if (chunk.type !== "chunk" || result.output.length !== 1)
  throw new Error("Expected one self-contained validator module.");
const source = await format(
  `/* Generated by npm run schema:generate. Ajv/ajv-formats/Rolldown MIT notices: THIRD_PARTY_NOTICES.md. */\n${chunk.code}`,
  { parser: "babel" },
);
if (
  /\brequire\(|\beval\(|new Function|https?:\/\//.test(
    source.replaceAll("https://json-schema.org/draft/2020-12/schema", ""),
  )
)
  throw new Error(
    "Unexpected standalone dependency or dynamic compilation: " +
      source
        .match(
          /.{0,40}(?:\brequire\(|\beval\(|new Function|https?:\/\/).{0,90}/g,
        )
        ?.join("\n"),
  );
if (source.includes(resolve(".")))
  throw new Error("Absolute workstation path in generated output.");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source)
    throw new Error("Profile validator is stale; run npm run schema:generate.");
  console.log("Profile validator matches published schema.");
} else writeFileSync(output, source);
